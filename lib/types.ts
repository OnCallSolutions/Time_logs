/**
 * Defines shared application data shapes for entries, approvals, and access roles.
 *
 * These types are imported by client components, API routes, and database helpers
 * so the app uses the same entry and role contracts across the stack.
 */
/**
 * Approval states supported by the timesheet workflow.
 *
 * Draft entries are still being reviewed by the employee, submitted entries are
 * ready for manager review, approved entries are accepted for reporting, and
 * rejected entries need employee correction before resubmission.
 */
export type EntryStatus = "draft" | "submitted" | "approved" | "rejected"

/**
 * Time entry persisted in Neon and rendered in the app UI.
 *
 * The id is generated by the database, core work fields are parsed or edited by
 * the user, and approval fields track the manager review lifecycle.
 */
export type TimeEntry = {
  /** Official company-issued number; not an authentication credential. */
  contractorNumber?: string
  shortReference?: string
  companyCode?: string
  employeeId?: string | null
  id: string
  /** Database evidence revision used to reject stale review decisions. */
  revision?: string
  /** Server-derived eligibility for the current caller's review lane. */
  reviewEligible?: boolean
  /** Server-derived approval capability, including business-account forwarding rights. */
  approvalEligible?: boolean
  /** Server-assigned record owner; never inferred from the display contractor name. */
  ownerEmail?: string
  /** Assigned operational manager; unassigned legacy submissions remain in the shared queue. */
  reviewManagerEmail?: string | null
  /** Display name resolved from the reviewer's registered company identity. */
  reviewManagerName?: string | null
  /** Display name resolved from the identity that recorded the decision. */
  reviewedByName?: string | null
  /** Evidence locked after explicit business-account eligibility authorization. */
  payoutEligible?: boolean
  contractor: string
  /** ISO date string: YYYY-MM-DD */
  date: string
  hours: number
  project: string
  description: string
  status: EntryStatus
  reviewedBy?: string | null
  reviewedAt?: string | null
  reviewNote?: string | null
}

/**
 * Shape returned by the AI parser before persistence.
 *
 * Parsed entries intentionally omit the database id because they are not durable
 * until the entries API stores them.
 */
export type ParsedEntry = Omit<
  TimeEntry,
  "id" | "contractorNumber" | "shortReference" | "companyCode" | "employeeId" | "revision" | "reviewEligible" | "approvalEligible" | "ownerEmail" | "reviewManagerEmail" | "payoutEligible" | "status" | "reviewedBy" | "reviewedAt" | "reviewNote"
>

/**
 * Role names supported by the navigation and API access rules.
 *
 * Admins and managers can view team-wide data, while employees and users are
 * scoped to entries owned by their signed-in email.
 */
export type UserRole = "admin" | "manager" | "account_manager" | "employee" | "contractor"

/**
 * Access states administrators can apply to managed app users.
 *
 * Only active users can enter with their assigned role. Denied represents an
 * onboarding/access request that was not approved; suspended is a temporary
 * business hold; retired means an employment or contractor engagement ended;
 * blocked is reserved for security containment. Historical records remain
 * separate from access state and are not deleted by these transitions.
 */
export type AccessStatus = "active" | "denied" | "suspended" | "retired" | "blocked"
