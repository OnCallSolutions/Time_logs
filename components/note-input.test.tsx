const period={id:"10000000-0000-4000-8000-000000000001",name:"Current period",startDate:"2026-01-01",endDate:"2026-12-31"}
function periodResponse(){return new Response(JSON.stringify({periods:[period]}))}
it("loads and extracts a synthetic Teams transcript scoped to the signed-in account",async()=>{
  const transcript="Synthetic Teams transcript: Own Person worked 2 hours on Sample Project."
  const request=vi.fn(async(input:string|URL|Request)=>{
    const url=String(input)
    if(url.includes("timesheet-periods"))return periodResponse()
    if(url.includes("teams-transcript"))return Response.json({notes:transcript,synthetic:true,transcript:true})
    if(url.includes("/api/parse"))return Response.json({entries:[{contractor:"Own Person",date:"2026-10-17",hours:2,project:"Sample Project",description:"Work"}]})
    return Response.json({projects:[{id:"p1",name:"Sample Project",description:""}]})
  })
  vi.stubGlobal("fetch",request);render(<NoteInput onParsed={()=>{}}/>)
  await userEvent.click(screen.getByRole("button",{name:"AI notes"}))
  await userEvent.click(screen.getByRole("button",{name:"Try sample transcript"}))
  expect(screen.getByRole("textbox",{name:"Time worked notes"})).toHaveValue(transcript)
  expect(screen.getByRole("button",{name:"Clear sample"})).toBeVisible()
  expect(screen.getByRole("textbox",{name:"Project for entry 1"})).toHaveValue("Sample Project")
  expect(request).toHaveBeenCalledWith(expect.stringContaining("/api/samples?format=teams-transcript"),{cache:"no-store"})
})
